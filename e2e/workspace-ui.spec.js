const { test, expect } = require('@playwright/test');
const { login, apiLogin, backendUrl, dismissCookieBanner } = require('./helpers');

test('administrator creates and edits an invoice, registers a service and sees the responsive overview', async ({ page, request }, testInfo) => {
    const auth = await apiLogin(request);
    const options = await (await request.get(`${backendUrl}/api/workspace/options`, { headers: { Authorization: `Bearer ${auth.token}` } })).json();
    const company = options.clients.find(x => x.name.includes('Horizon'));
    const suffix = Date.now();
    await login(page, 'platform_admin', 'admin123');
    await expect(page).toHaveURL(/\/app\/admin\/clients/);
    await page.goto('/app/admin/invoices');
    await page.getByRole('button', { name: 'Nueva factura' }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('combobox', { name: 'Empresa', exact: true }).selectOption(company.id);
    await dialog.getByLabel('Número de factura').fill(`UI-${suffix}`);
    await dialog.getByLabel('Importe', { exact: true }).fill('100,00');
    await dialog.getByRole('button', { name: 'Guardar factura' }).click();
    await expect(page.getByText('Factura registrada.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: `Editar factura UI-${suffix}`, exact: true }).click();
    await dialog.getByLabel('Importe', { exact: true }).fill('125,00');
    await dialog.getByRole('button', { name: 'Guardar cambios' }).click();
    await expect(page.getByText('Factura actualizada.', { exact: true })).toBeVisible();
    await expect(page.getByRole('row').filter({ hasText: `UI-${suffix}` })).toContainText('125,00');
    await page.goto('/app/admin/service-records');
    await page.getByRole('button', { name: 'Registrar servicio' }).click();
    await dialog.getByRole('combobox', { name: 'Empresa', exact: true }).selectOption(company.id);
    await dialog.getByLabel('Nombre del servicio').fill(`Servicio de prueba UI ${suffix}`);
    await dialog.getByLabel('Fecha de trabajo').fill('2026-11-03');
    await dialog.getByLabel('Coste registrado').fill('25,50');
    await dialog.getByRole('button', { name: 'Guardar servicio' }).click();
    await expect(dialog).toBeHidden();
    await page.getByLabel(`Estado de Servicio de prueba UI ${suffix}`, { exact: true }).selectOption('COMPLETED');
    await expect(page.getByRole('article').filter({ hasText: `Servicio de prueba UI ${suffix}` })).toContainText('Finalizado');
    await page.goto('/app/admin/overview');
    await expect(page.getByRole('heading', { name: 'Una visión clara de tu operación.' })).toBeVisible();
    await expect(page.getByText('Cargando información…', { exact: true })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('dashboard-admin.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Abrir menú' }).click();
    await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Servicios', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Servicios y trabajos' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Abrir menú' })).toHaveAttribute('aria-expanded', 'false');
});

